/**
 * Las clases de un botón, ya fusionadas con `cn`. Sin fusionar, la base
 * (`border-transparent`) le gana a la variante (`border-border` de `outline`)
 * cuando se usa fuera de `<Button>`, por ejemplo en un `<Link>` (docs/13).
 */
function buttonVariants(
  props?: Parameters<typeof buttonVariantsBase>[0]
): string {
  return cn(buttonVariantsBase(props))
}

function Button({
  className,
  variant = "default",
  size = "default",
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof buttonVariants>) {
  return (
    <ButtonPrimitive
      data-slot="button"
      className={cn(buttonVariants({ variant, size, className }))}
      {...props}
    />
  )
}

export { Button, buttonVariants }
