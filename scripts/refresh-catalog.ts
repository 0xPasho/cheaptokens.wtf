import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { CATALOG } from "../catalog/models";
import { importInferhubCatalog, INFERHUB_CATALOG_URL } from "../src/lib/catalog/inferhub-import";
import { validateCatalog } from "../src/lib/catalog/validate";
import type { UpstreamDefinition } from "../src/lib/catalog/types";

async function main() {
  const response = await fetch(INFERHUB_CATALOG_URL, { signal: AbortSignal.timeout(30_000), redirect: "error" });
  if (!response.ok) throw new Error(`Official catalog failed (HTTP ${response.status}); existing files were retained`);
  const imported = importInferhubCatalog(await response.json(), CATALOG);
  const upstream: UpstreamDefinition = {
    id: "inferhub", name: "InferHub", baseUrl: "https://api.inferhub.dev/v1", apiKeyEnv: "UPSTREAM_INFERHUB_API_KEY",
    sendsPriceCap: true, environments: ["development", "preview", "production"], models: imported.mappings,
  };
  const validation = validateCatalog({ models: imported.models, upstreams: [upstream], environment: "production" });
  if (validation.errors.length) throw new Error(`Official catalog validation failed:\n${validation.errors.join("\n")}`);
  const directory = new URL("../catalog/generated/", import.meta.url);
  await mkdir(directory, { recursive: true });
  const serialize = (name: string, type: string, data: unknown) => `// Generated by pnpm catalog:refresh. Do not edit manually.\nimport type { ${type} } from "@/lib/catalog/types";\n\nexport const ${name}: ${type}[] = ${JSON.stringify(data, null, 2)};\n`;
  await writeFile(new URL("models.ts", directory), serialize("IMPORTED_MODELS", "CatalogEntry", imported.models));
  await writeFile(new URL("inferhub-mappings.ts", directory), serialize("INFERHUB_MODELS", "UpstreamModelMapping", imported.mappings));
  await writeFile(new URL("import-report.json", directory), JSON.stringify({ source: INFERHUB_CATALOG_URL, fetchedAt: new Date().toISOString(), ...imported.report }, null, 2) + "\n");
  console.log(`Official catalog: ${imported.report.published} models from ${imported.report.received} entries. ${imported.report.retired} retired IDs retained.`);
  console.log(`Written to ${fileURLToPath(directory)}. Run pnpm catalog:sync to update the gateway database.`);
}

void main().catch((error: unknown) => { console.error(error instanceof Error ? error.message : "Catalog refresh failed"); process.exitCode = 1; });
